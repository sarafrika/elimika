package apps.sarafrika.elimika.wallet.dto;

import com.fasterxml.jackson.annotation.JsonProperty;
import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Positive;
import jakarta.validation.constraints.Size;
import java.math.BigDecimal;
import java.util.UUID;

@Schema(name = "WithdrawalRequest", description = "How much to withdraw and to which verified number")
public record WithdrawalRequestDTO(
        @Schema(description = "Whole shillings", example = "1500", requiredMode = Schema.RequiredMode.REQUIRED)
        @NotNull @Positive
        @JsonProperty("amount") BigDecimal amount,
        @Schema(requiredMode = Schema.RequiredMode.REQUIRED)
        @NotNull
        @JsonProperty("payout_method_uuid") UUID payoutMethodUuid,
        @Schema(description = "Generated by the client per attempt; repeating it returns the first withdrawal",
                requiredMode = Schema.RequiredMode.REQUIRED)
        @NotBlank @Size(max = 80)
        @JsonProperty("idempotency_key") String idempotencyKey
) {
}
